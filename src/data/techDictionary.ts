/**
 * Translates a single tech stack badge/string into the active language.
 * Falls back to the original string if no translation is needed or found.
 */
export function translateTech(tech: string, language: string): string {
  if (!tech) return "";
  if (language === "en") return tech;

  const match = techStackDictionary[tech.trim()];
  if (match) {
    if (language === "zh" && match.zh) return match.zh;
    if (language === "id" && match.id) return match.id;
  }

  return tech;
}

/**
 * Translates action buttons and demo links (e.g. "Watch on YouTube", "Corporate Video Profile", etc.)
 */
export function translateActionLabel(label: string, language: string): string {
  if (!label) return "";
  if (language === "en") return label;

  const match = actionLabelDictionary[label.trim()];
  if (match) {
    if (language === "zh" && match.zh) return match.zh;
    if (language === "id" && match.id) return match.id;
  }

  // Common pattern translations
  if (language === "zh") {
    if (label.includes("Watch on YouTube")) return "前往 YouTube 观看";
    if (label.includes("Watch on Instagram")) return "前往 Instagram 观看";
    if (label.includes("GitHub Repository")) return label.replace("GitHub Repository", "GitHub 源码仓库");
    if (label.includes("Live Demo")) return "在线演示";
    if (label.includes("YouTube Channel")) return "YouTube 官方频道";
    if (label.includes("Storefront")) return "官方在线店铺";
    if (label.includes("Template")) return label.replace("Template", "模板");
  } else if (language === "id") {
    if (label.includes("Watch on YouTube")) return "Tonton di YouTube";
    if (label.includes("Watch on Instagram")) return "Tonton di Instagram";
    if (label.includes("GitHub Repository")) return label.replace("GitHub Repository", "Repositori GitHub");
    if (label.includes("Live Demo")) return "Demo Langsung";
    if (label.includes("YouTube Channel")) return "Kanal YouTube";
    if (label.includes("Storefront")) return "Toko Resmi";
    if (label.includes("Template")) return label.replace("Template", "Template");
  }

  return label;
}
